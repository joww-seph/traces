import { expect, test } from '@playwright/test'
import { a11y, apiSeed, apiSign, login, noHorizontalScroll } from './helpers'

// Runs after app.spec.ts in the same database: officers JDelaCruz and MSantos already exist.
test.describe.configure({ mode: 'serial' })

const nos = { main: '2026-09ICT-0301', part: '2026-09ICT-0301a', semi: '2026-09ICT-0302' }
let icsId = ''
let parId = ''
let cardId = ''
let tokens: Record<string, string> = {}

test('seed: an issuance with a PPE laptop set and a semi chair, forms generated', async ({ page }) => {
  await login(page)
  const s = await apiSeed(page, '2026-05D2-001', nos)
  icsId = s.icsId
  parId = s.parId
  cardId = await s.itemId(nos.main)
  tokens = { main: await s.token(nos.main), part: await s.token(nos.part), semi: await s.token(nos.semi) }
  expect(tokens.main).toMatch(/^[0-9A-Za-z]{10}$/)
})

test('a scan opens the property without signing in: the generated form with its box and an "unsigned" banner, four tabs, each with its row highlighted', async ({ browser }) => {
  const ctx = await browser.newContext()
  const page = await ctx.newPage()
  await page.goto(`/q/${tokens.main}`)
  await expect(page.getByRole('heading', { name: 'Laptop', level: 1 })).toBeVisible()
  await expect(page.getByRole('tab')).toHaveText(['ICS/PAR', 'Report', 'Registry', 'Card'])
  await expect(page.getByText('Unsigned copy generated by TRACES')).toBeVisible()
  await expect(page.getByTestId('region-highlight')).toBeVisible() // the box, computed from the layout, over the PAR row
  await expect(page.locator('.traces-highlight')).toHaveCount(1) // the line in the PAR grid
  await page.getByRole('tab', { name: 'Report' }).click()
  await expect(page.getByText('REPORT ON THE PHYSICAL COUNT OF PROPERTY, PLANT AND EQUIPMENT')).toBeVisible()
  await expect(page.locator('.traces-highlight')).toHaveCount(1)
  await page.getByRole('tab', { name: 'Registry' }).click()
  await expect(page.locator('.traces-highlight')).toHaveCount(1)
  await expect(page.getByText('REGISTRY OF PROPERTY, PLANT AND EQUIPMENT ISSUED')).toBeVisible()
  await page.getByRole('tab', { name: 'Card' }).click()
  await expect(page.locator('.traces-highlight')).toHaveCount(2) // the receipt and the issue of this line
  await expect(page).toHaveURL(/#card$/)
  await ctx.close()
})

