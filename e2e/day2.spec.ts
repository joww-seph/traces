test('accessibility: scan page, property page, registry, cards, stickers', async ({ page, browser }) => {
  const ctx = await browser.newContext()
  const anon = await ctx.newPage()
  await anon.goto(`/q/${tokens.semi}`)
  await expect(anon.getByRole('heading', { name: 'Office chair', level: 1 })).toBeVisible()
  for (const tab of ['ICS/PAR', 'Report', 'Registry', 'Card']) {
    await anon.getByRole('tab', { name: tab }).click()
    await anon.waitForLoadState('networkidle')
    expect(await a11y(anon), `scan page / ${tab}`).toEqual([])
  }
  await ctx.close()
  await login(page)
  for (const p of ['/registry', `/properties/${nos.semi}`, `/cards/${cardId}`, `/stickers?documentId=${icsId}`, '/stickers']) {
    await page.goto(p)
    await page.waitForLoadState('networkidle')
    await page.waitForTimeout(600)
    expect(await a11y(page), p).toEqual([])
  }
})
