test('a PDF that fails to load (e.g. too many scans) leaves the scan page working', async ({ browser }) => {
  const ctx = await browser.newContext()
  const anon = await ctx.newPage()
  await anon.route('**/api/public/q/*/pdf', (r) => r.fulfill({ status: 429, contentType: 'application/json', body: '{"code":"RATE_LIMITED"}' }))
  await anon.goto(`/q/${tokens.semi}`)
  await expect(anon.getByText('Could not load the PDF.')).toBeVisible()
  await expect(anon.getByRole('heading', { name: 'Office chair', level: 1 })).toBeVisible()
  await anon.getByRole('tab', { name: 'Card' }).click()
  await expect(anon.getByRole('tabpanel')).toBeVisible()
  await ctx.close()
})

test('an older phone browser without Map.getOrInsertComputed still shows the scanned form', async ({ browser }) => {
  const ctx = await browser.newContext()
  await ctx.addInitScript(() => {
    for (const C of [Map, WeakMap]) for (const k of ['getOrInsert', 'getOrInsertComputed']) delete (C.prototype as unknown as Record<string, unknown>)[k]
  })
  const anon = await ctx.newPage()
  await anon.goto(`/q/${tokens.main}`)
  await expect(anon.locator('.react-pdf__Page__canvas')).toBeVisible()
  await expect(anon.getByTestId('region-highlight')).toBeVisible()
  await expect(anon.getByText('Unexpected Application Error')).toHaveCount(0)
  await ctx.close()
})

